def esc(v) -> str:
    return html.escape(str(v), quote=True)


def fmt(v, digits: int = 2) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        if v != v:
            return "—"
        if v == int(v) and abs(v) < 1e15:
            return f"{int(v):,}"
        return f"{v:,.{digits}f}"
    return str(v)


def pct(v, digits: int = 1) -> str:
    if v is None or (isinstance(v, float) and v != v):
        return "—"
    return f"{v * 100:,.{digits}f}%"


def link(url: str, text: str) -> str:
    return f'<a href="{esc(url)}" target="_blank" rel="noopener noreferrer">{esc(text)} </a>'


def badge(passed: bool | None) -> str:
    if passed is None:
        return '<span class="pill pill-unknown">not established</span>'
    return ('<span class="pill pill-pass">pass</span>' if passed
            else '<span class="pill pill-fail">fail</span>')


def unverified(note: str = "unverified") -> str:
    return f'<span class="unverified" title="{esc(note)}">— unverified</span>'


